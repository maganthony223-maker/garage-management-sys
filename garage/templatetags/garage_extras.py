@register.simple_tag
def icon(name, size=18):
    body = ICONS.get(name, '')
    return mark_safe(
        f'<svg class="ic" width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" '
        f'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
        f'aria-hidden="true">{body}</svg>')


@register.filter
def money(value):
    try:
        n = Decimal(value or 0)
    except (InvalidOperation, TypeError):
        return value
    return f'{CURRENCY} {n:,.0f}'


@register.filter
def get_attr(obj, name):
    value = getattr(obj, name, '')
    if callable(value):
        value = value()
    if hasattr(obj, f'get_{name}_display'):
        return getattr(obj, f'get_{name}_display')()
    if name in MONEY_ATTRS:
        return money(value)
    if value is True:
        return 'Yes'
    if value is False:
        return 'No'
    return '' if value is None else value
